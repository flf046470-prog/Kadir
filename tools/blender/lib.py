"""
Shared Blender helpers for generating the game's art.

Why the art is generated by a script rather than downloaded or drawn by hand:

  * **Licence.** The game is web-delivered, so every file the server sends can be pulled out of
    the browser by any player. That makes "may end users extract the raw asset?" a question we
    cannot answer with "no", and it is the reason `assets/packs.json` refuses anything but CC0,
    CC-BY and permissive sources. Geometry produced by this script is original work, so the
    question does not arise at all.
  * **Reproducibility.** A binary in a repository with no source is a dead end — nobody can fix a
    proportion or recolour a body six months later. Every model here is a seeded function of the
    game's own data, so regenerating is `npm run assets:build` and the diff is reviewable.
  * **It cannot drift from the game.** Colours, proportions and body plans are read from
    `tools/blender/animals.json`, which is dumped straight out of `LAUNCH_ANIMALS`. Recolouring
    an animal in the game data recolours the model; there is no second copy to forget.

Conventions, which matter because getting them wrong is invisible until the model is in a match:

  * **Units are metres**, matching the simulation.
  * **Origin at the feet.** `MovementConfig.position` is the point the feet stand on, so a model
    centred on its body floats or sinks by half its height.
  * **Forward is +Y in Blender.** The glTF exporter maps Blender's Z-up to glTF's Y-up, sending
    Blender +Y to glTF -Z — which is the direction three.js treats as forward. Build facing +Y
    and the character faces where it walks.
  * **Flat shading, no textures.** Colour comes from per-material base colour, which keeps files
    in the low tens of kilobytes and matches the chunky low-poly look the rest of the art uses.
    A texture would be the single biggest thing in the download budget.
"""

import math
import os

import bpy
from mathutils import Euler, Matrix, Quaternion, Vector

# --------------------------------------------------------------------------------------------
# Scene
# --------------------------------------------------------------------------------------------


def reset() -> None:
    """An empty scene with nothing inherited from a previous build in it."""
    bpy.ops.wm.read_factory_settings(use_empty=True)
    # Actions survive a factory reset when they carry a fake user, and a stale action from a
    # previous animal would be exported into the next one's file as a bonus animation.
    for block in (bpy.data.actions, bpy.data.materials, bpy.data.meshes, bpy.data.armatures):
        for item in list(block):
            block.remove(item)


def hex_to_linear(value: int) -> tuple:
    """
    A game-data colour (0xRRGGBB) as Blender's linear RGBA.

    The conversion is not decoration. Blender works in linear space and glTF stores base colour
    in sRGB; handing a raw 0..1 sRGB value straight to a material makes every model come out
    visibly washed out against the UI colours taken from the same hex.
    """
    srgb = ((value >> 16) & 0xFF) / 255.0, ((value >> 8) & 0xFF) / 255.0, (value & 0xFF) / 255.0

    def to_linear(c: float) -> float:
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    return (to_linear(srgb[0]), to_linear(srgb[1]), to_linear(srgb[2]), 1.0)


_materials: dict = {}


def material(name: str, hex_colour: int, roughness: float = 0.75) -> bpy.types.Material:
    """A flat solid-colour material, created once per name."""
    key = (name, hex_colour)
    if key in _materials:
        return _materials[key]
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = hex_to_linear(hex_colour)
    bsdf.inputs["Roughness"].default_value = roughness
    # Metallic stays at zero: a stylised animal that catches specular highlights like a car reads
    # as plastic, and every glTF viewer defaults metallic to 1.0 if the input is left unset.
    bsdf.inputs["Metallic"].default_value = 0.0
    _materials[key] = mat
    return mat


def reset_materials() -> None:
    _materials.clear()


