def armature(name, bones):
    """
    Build an armature from `(bone_name, head, tail, parent_or_None)` tuples, in order.

    Parents must appear before their children, which is checked rather than assumed: a bone whose
    parent is missing is silently rooted at the origin, and the result is a limb that swings from
    the middle of the world.
    """
    arm_data = bpy.data.armatures.new(name)
    arm_obj = bpy.data.objects.new(name, arm_data)
    bpy.context.scene.collection.objects.link(arm_obj)
    bpy.context.view_layer.objects.active = arm_obj
    bpy.ops.object.mode_set(mode="EDIT")

    made = set()
    for bone_name, head, tail, parent in bones:
        if parent is not None and parent not in made:
            raise ValueError(f"bone {bone_name!r} names parent {parent!r} before it exists")
        eb = arm_data.edit_bones.new(bone_name)
        eb.head = Vector(head)
        eb.tail = Vector(tail)
        if (eb.tail - eb.head).length < 1e-4:
            raise ValueError(f"bone {bone_name!r} has zero length; Blender would drop it")
        if parent is not None:
            eb.parent = arm_data.edit_bones[parent]
        made.add(bone_name)

    bpy.ops.object.mode_set(mode="OBJECT")
    return arm_obj


def bone_socket(arm_obj, bone_name: str, name: str, world_pos) -> "bpy.types.Object":
    """
    An empty parented to a bone, placed at a world position, exported as a named glTF node.

    This is how a model tells the renderer where a hat goes. It rides the bone, so a hat follows
    the head through every clip, and it is placed in *world* space after parenting, because a
    bone-parented object's local frame starts at the bone's tail and points along the bone — a
    literal offset would mean something different on every body plan.
    """
    if bone_name not in arm_obj.data.bones:
        raise KeyError(f"socket {name!r} names bone {bone_name!r}, which this rig does not have")
    empty = bpy.data.objects.new(name, None)
    bpy.context.scene.collection.objects.link(empty)
    empty.empty_display_size = 0.05
    empty.parent = arm_obj
    empty.parent_type = "BONE"
    empty.parent_bone = bone_name
    bpy.context.view_layer.update()
    empty.matrix_world = Matrix.Translation(Vector(world_pos))
    bpy.context.view_layer.update()
    return empty


def skin(mesh_obj, arm_obj) -> None:
    """Bind mesh to armature with automatic (heat-diffusion) weights."""
    bpy.ops.object.select_all(action="DESELECT")
    mesh_obj.select_set(True)
    arm_obj.select_set(True)
    bpy.context.view_layer.objects.active = arm_obj
    bpy.ops.object.parent_set(type="ARMATURE_AUTO")
    if not any(m.type == "ARMATURE" for m in mesh_obj.modifiers):
        raise RuntimeError(f"{mesh_obj.name} did not receive an armature modifier")


def _convex_solids(parts):
    """Each part as (name, world vertices, outward face normals, plane offsets)."""
    import numpy as np

    bpy.context.view_layer.update()
    solids = []
    for p in parts:
        mw = p.matrix_world
        verts = np.array([tuple(mw @ v.co) for v in p.data.vertices])
        normals, offsets = [], []
        for f in p.data.polygons:
            a = mw @ p.data.vertices[f.vertices[0]].co
            b = mw @ p.data.vertices[f.vertices[1]].co
            c = mw @ p.data.vertices[f.vertices[2]].co
            n = (b - a).cross(c - a)
            if n.length < 1e-12:
                continue
            n.normalize()
            normals.append(tuple(n))
            offsets.append(n.dot(a))
        solids.append((p.name, verts, np.array(normals), np.array(offsets)))
    return solids


def detached_parts(parts, reach: float = 0.01) -> list:
    """
    Parts that touch no other part: a tail, an ear or a hand floating free of the body.

    Measured by rendering, not by reading: every waddler's stub tail hung twelve centimetres
    behind the body, because the egg narrows at hip height and the tail was placed against the
    widest part of it. Nothing about the numbers looked wrong. A part is attached when any of its
    vertices lies within `reach` of the inside of another part, or another part's vertex lies
    within `reach` of the inside of it — the same exact convex test as `hidden_parts`, loosened
    by a centimetre so that two parts meeting face to face count as touching.
    """
    import numpy as np

    solids = _convex_solids(parts)
    touching = {name: False for name, *_ in solids}
    for i, (name, verts, _n, _d) in enumerate(solids):
        for j, (other, _v, normals, offsets) in enumerate(solids):
            if i == j or len(normals) == 0:
                continue
            if np.any(np.all(verts @ normals.T - offsets < reach, axis=1)):
                touching[name] = touching[other] = True
    return [name for name, ok in touching.items() if not ok]


def hidden_parts(parts, threshold: float = 0.97) -> list:
    """
    Parts whose vertices lie almost entirely inside other parts, as `(name, fraction)` pairs.

    Such a part draws nothing, and it is not merely waste: a closed island no bone can see gives
    heat-diffusion weighting a singular block. A draft of the upright plan had one — a neck
    enclosed by the shoulders and the skull on all seven upright animals — and the solve then
    failed or not on floating-point summation order, 3 skins in 320, each time leaving over a
    thousand vertices on no bone at all. On the shipped plans the most-hidden part is 83 % hidden
    (a belly set into a torso), so the default threshold leaves a real margin.

    Exact rather than approximate, because every part this generator builds is convex (spheres,
    boxes, cones, and affine images of them): a point is inside a convex solid exactly when it is
    behind every one of its face planes. A first version compared against the nearest face's normal
    and reported whole eyes as hidden on one side of a head and not the other — wrong at edges,
    where the nearest face is not the face the point is behind.
    """
    import numpy as np

    solids = _convex_solids(parts)
    hidden = []
    for name, verts, _n, _d in solids:
        inside = np.zeros(len(verts), dtype=bool)
        for other, _v, normals, offsets in solids:
            if other == name or len(normals) == 0:
                continue
            # Behind every plane by a millimetre: touching a surface is not being hidden by it.
            inside |= np.all(verts @ normals.T - offsets < -1e-3, axis=1)
        fraction = float(inside.mean()) if len(verts) else 0.0
        if fraction >= threshold:
            hidden.append((name, round(fraction, 3)))
    return hidden


PIN_PREFIX = "pin:"


def pin(ob, bone_name: str):
    """
    Mark a part, before `join`, as riding one bone rigidly.

    Stored as a vertex group named `pin:<bone>`, which survives joining (groups merge by name) and
    automatic weighting (which only writes groups named after bones). `apply_pins` turns it into
    a full weight on that bone afterwards.
    """
    group = ob.vertex_groups.new(name=PIN_PREFIX + bone_name)
    group.add([v.index for v in ob.data.vertices], 1.0, "REPLACE")
    return ob


def apply_pins(mesh_obj) -> int:
    """Give every pinned vertex a single full weight on its bone, and drop the pin groups."""
    moved = 0
    for pin_group in [g for g in mesh_obj.vertex_groups if g.name.startswith(PIN_PREFIX)]:
        bone_name = pin_group.name[len(PIN_PREFIX):]
        target = mesh_obj.vertex_groups.get(bone_name) or mesh_obj.vertex_groups.new(name=bone_name)
        members = [v.index for v in mesh_obj.data.vertices if any(g.group == pin_group.index for g in v.groups)]
        for vi in members:
            for g in list(mesh_obj.data.vertices[vi].groups):
                if g.group not in (target.index, pin_group.index):
                    mesh_obj.vertex_groups[g.group].remove([vi])
        target.add(members, 1.0, "REPLACE")
        mesh_obj.vertex_groups.remove(pin_group)
        moved += len(members)
    return moved


def unweighted_vertices(mesh_obj) -> int:
    """Vertices with no bone weight at all — each one is bound to the exporter's `neutral_bone`."""
    bone_groups = {g.index for g in mesh_obj.vertex_groups if not g.name.startswith(PIN_PREFIX)}
    return sum(1 for v in mesh_obj.data.vertices if not any(g.group in bone_groups and g.weight > 1e-4 for g in v.groups))


