def box(name, center, size, mat, rotation=(0.0, 0.0, 0.0)):
    """An axis-aligned box. `size` is full width/depth/height, not half-extents."""
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=center)
    ob = bpy.context.active_object
    ob.name = name
    ob.scale = (size[0], size[1], size[2])
    ob.rotation_euler = Euler(rotation, "XYZ")
    _finish(ob, mat)
    return ob


def sphere(name, center, size, mat, segments=10, rings=6, rotation=(0.0, 0.0, 0.0)):
    """
    A low-polygon UV sphere, scaled per axis so one call covers heads, bellies and berries.

    Deliberately coarse: at 10x6 a sphere is 108 triangles, which reads as a rounded form at
    gameplay distance and costs a twentieth of what Blender's default would.
    """
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segments, ring_count=rings, radius=0.5, location=center)
    ob = bpy.context.active_object
    ob.name = name
    ob.scale = (size[0], size[1], size[2])
    # Optional so every existing call keeps its geometry bit-for-bit. A limb or a tail segment
    # running along a diagonal needs its long axis along that diagonal: an axis-aligned ellipsoid
    # laid on a slope reads as a flat disc, and a chain of them reads as loose lumps.
    ob.rotation_euler = Euler(rotation, "XYZ")
    _finish(ob, mat)
    return ob


def cone(name, center, radius1, radius2, depth, mat, vertices=8, rotation=(0.0, 0.0, 0.0)):
    """A truncated cone — ears, snouts, tails, tree trunks."""
    bpy.ops.mesh.primitive_cone_add(
        vertices=vertices, radius1=radius1, radius2=radius2, depth=depth, location=center
    )
    ob = bpy.context.active_object
    ob.name = name
    ob.rotation_euler = Euler(rotation, "XYZ")
    _finish(ob, mat)
    return ob


def wedge(name, center, size, mat, rotation=(0.0, 0.0, 0.0)):
    """
    A fin: a right triangle standing in the YZ plane, extruded `size[0]` thick along X.

    The base runs along the bottom the full depth `size[1]`, and the apex sits above the *back*
    end, so the leading edge sweeps back the way a dorsal fin, a tail fluke or a shark's ear does.
    Fins used to be boxes, and from the side a shark read as three dark squares.

    Faces are wound outward on purpose: `hidden_parts` and `detached_parts` treat every part as a
    convex solid bounded by its face planes, so a reversed face would put the inside outside.
    """
    w, d, h = size[0] / 2, size[1] / 2, size[2] / 2
    verts = [(-w, d, -h), (-w, -d, -h), (-w, -d, h), (w, d, -h), (w, -d, -h), (w, -d, h)]
    # left (-X), right (+X), bottom (-Z), back (-Y), leading edge (+Y+Z)
    faces = [(0, 1, 2), (3, 5, 4), (0, 3, 4, 1), (1, 4, 5, 2), (0, 2, 5, 3)]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    ob = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(ob)
    ob.location = center
    ob.rotation_euler = Euler(rotation, "XYZ")
    _finish(ob, mat)
    return ob


def _finish(ob, mat) -> None:
    ob.data.materials.append(mat)
    for poly in ob.data.polygons:
        poly.use_smooth = False


def join(parts, name):
    """
    One mesh from many primitives.

    Joining before skinning is what makes automatic weights usable: separate objects each get
    their own armature modifier and their own weight solve, and the seams between them tear open
    the moment a bone rotates.
    """
    parts = [p for p in parts if p is not None]
    bpy.ops.object.select_all(action="DESELECT")
    for p in parts:
        p.select_set(True)
    bpy.context.view_layer.objects.active = parts[0]
    bpy.ops.object.join()
    ob = bpy.context.active_object
    ob.name = name
    # Scale and rotation are baked in now, while the mesh is still unskinned. Leaving a non-unit
    # scale on the object makes the armature deform in the wrong space and is close to impossible
    # to diagnose from the result.
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=True)
    return ob


def join_into(target, parts):
    """
    Join `parts` into an existing mesh, which keeps its own modifiers, parent and vertex groups.

    For pinned parts after skinning: see `characters.skin_parts`.
    """
    parts = [p for p in parts if p is not None]
    if not parts:
        return target
    bpy.ops.object.select_all(action="DESELECT")
    target.select_set(True)
    for p in parts:
        p.select_set(True)
    bpy.context.view_layer.objects.active = target
    bpy.ops.object.join()
    return target


def is_pinned(ob) -> bool:
    return any(g.name.startswith(PIN_PREFIX) for g in ob.vertex_groups)


def triangle_count(ob) -> int:
    ob.data.calc_loop_triangles()
    return len(ob.data.loop_triangles)


